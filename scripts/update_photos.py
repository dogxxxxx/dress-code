"""Build the static photo list. Run from any directory with Python 3."""
import json
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = {
    "male": "images/male",
    "pants": "images/female/pants",
    "skirts": "images/female/skirts",
    "group": "images/group",
}
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".svg"}
photos = {}
for category, folder in FOLDERS.items():
    files = sorted((ROOT / folder).iterdir(), key=lambda path: path.name.casefold())
    photos[category] = [quote(path.relative_to(ROOT).as_posix(), safe="/")
                        for path in files if path.is_file() and path.suffix.lower() in EXTENSIONS]
(ROOT / "js/photos.js").write_text(
    "// Generated by scripts/update_photos.py\nwindow.dressCodePhotos = "
    + json.dumps(photos, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
for category, paths in photos.items():
    print(f"{category}: {len(paths)} photos")
